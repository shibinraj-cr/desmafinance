/**
 * Excel statements from net banking (src/lib/bank/parsers/spreadsheet.ts):
 * HDFC's .xls and Axis's .xlsx, laid out like the real downloads (header
 * block, table, totals), with made-up names, accounts and amounts — the
 * repository is public. Also the continuity rule between statements and the
 * "same line from another file" duplicate guard.
 */
