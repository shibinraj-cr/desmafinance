const TODAY = "2026-11-18";
const check = (p: ReturnType<typeof parseStatementWorkbook>["parsed"], last4: string) =>
  validateStatement(p, { last4, periodStart: p.periodStart, periodEnd: p.periodEnd, today: TODAY });

describe("HDFC .xls", () => {
  const { bankCode, parsed } = parseStatementWorkbook(hdfc());

  it("names its bank, account and period", () => {
    expect(bankCode).toBe("HDFC");
    expect(parsed.accountNumber).toBe("50200000001234");
    expect([parsed.periodStart, parsed.periodEnd]).toEqual(["2026-11-01", "2026-11-30"]);
  });

  it("reads every row with its date, reference, side and balance in paise", () => {
    expect(parsed.rows.map((r) => [r.txnDate, r.referenceNumber, r.debit, r.credit, r.balance])).toEqual([
      ["2026-11-01", "0000612345678901", 0, 3422000, 13422000],
      ["2026-11-03", "TEST0000123", 0, 5000000, 18422000],
      ["2026-11-05", "0000000000001", 150050, 0, 18271950],
    ]);
    expect(parsed.rows[0].description).toBe("UPI-TEST CANDIDATE ONE-ONE@OKBANK-612345678901");
  });

  it("takes the opening and closing balance and the counts from the summary, and validates", () => {
    expect(parsed.openingBalance).toBe(10000000);
    expect(parsed.closingBalance).toBe(18271950);
    expect(parsed.summary).toMatchObject({ totalDebit: 150050, totalCredit: 8422000, debitCount: 1, creditCount: 2 });
    expect(check(parsed, "1234").errors).toEqual([]);
  });

  it("holds a statement whose rows don't add up to its own summary", () => {
    const off = parseStatementWorkbook(hdfc({ summary: [100000, "", "", "", 1500.5, 90000, 182719.5] })).parsed;
    expect(check(off, "1234").errors).toContain("Total credits differ from the statement summary");
    const counts = parseStatementWorkbook(hdfc({ counts: ["", "", "", "", 2, 2] })).parsed;
    expect(check(counts, "1234").errors).toContain("Summary shows 2 debits, 1 were read");
  });

  it("joins a narration wrapped onto its own row", () => {
    const { parsed: p } = parseStatementWorkbook(
      hdfc({
        rows: [
          ["01/11/26", "NEFT CR-TEST0000123-A VERY LONG", "TEST0000123", "01/11/26", "", 84220, 184220],
          ["", "PAYER NAME THAT WRAPS", "", "", "", "", ""],
          ["05/11/26", "POS 1234XXXX TEST STORE", "0000000000001", "05/11/26", 1500.5, "", 182719.5],
        ],
      }),
    );
    expect(p.rows).toHaveLength(2);
    expect(p.rows[0].description).toBe("NEFT CR-TEST0000123-A VERY LONG PAYER NAME THAT WRAPS");
  });

  it("refuses an HDFC file uploaded against an Axis account", () => {
    expect(() => parseStatementWorkbook(hdfc(), "AXIS")).toThrow(/HDFC statement, not AXIS/);
  });
});

describe("Axis .xlsx", () => {
  const { bankCode, parsed } = parseStatementWorkbook(axis());

  it("finds the columns despite the '(dd/mm/yyyy)' and '(INR)' hints", () => {
    expect(headerKey("Transaction Date (dd/mm/yyyy)")).toBe("transaction date");
    expect(headerKey("Amount(INR)")).toBe("amount");
    expect(bankCode).toBe("AXIS");
    expect(parsed.accountNumber).toBe("922020000001234");
    expect([parsed.periodStart, parsed.periodEnd]).toEqual(["2026-11-01", "2026-11-12"]);
  });

  it("reads one amount + DR/CR into the right side, Indian grouping and all", () => {
    expect(parsed.rows.map((r) => [r.txnDate, r.debit, r.credit, r.balance])).toEqual([
      ["2026-11-03", 0, 3422000, 13422000],
      ["2026-11-04", 9084400, 0, 4337600],
      ["2026-11-04", 1000000, 0, 3337600],
    ]);
  });

  it("takes the opening, closing and DR/CR totals from the table's own rows, and validates", () => {
    expect(parsed.openingBalance).toBe(10000000);
    expect(parsed.closingBalance).toBe(3337600);
    expect(parsed.summary).toMatchObject({ totalDebit: 10084400, totalCredit: 3422000 });
    expect(check(parsed, "1234").errors).toEqual([]);
  });

  it("holds a statement whose closing balance doesn't follow from its rows", () => {
    const p = parseStatementWorkbook(axis({ closing: "33,000.00" })).parsed;
    expect(check(p, "1234").errors).toContain("Opening balance + credits − debits does not equal the closing balance");
  });
});

describe("cells", () => {
  it("reads a date Excel converted on a re-save from its serial", () => {
    expect(sheetDate(46336)).toBe("2026-11-10");
    expect(sheetDate("10/11/26")).toBe("2026-11-10");
    expect(sheetDate("10-Nov-2026")).toBe("2026-11-10");
    expect(sheetDate("31/02/2026")).toBeNull();
  });

  it("reads money as integer paise", () => {
    expect(sheetAmount("1,23,456.78")).toBe(12345678);
    expect(sheetAmount(1500.5)).toBe(150050);
    expect(sheetAmount("")).toBeNull();
    expect(sheetAmount("-")).toBeNull();
  });

  it("only takes Excel files", () => {
    expect(looksLikeSpreadsheet(new TextEncoder().encode("%PDF-1.7 …"))).toBe(false);
    expect(() => parseStatementWorkbook(new TextEncoder().encode("Date,Narration\n"))).toThrow(/not an Excel statement/);
  });
});

describe("continuity between statements", () => {
  const me = { periodStart: "2026-11-01", periodEnd: "2026-11-30", openingBalance: 10000000, closingBalance: 18271950 };

  it("passes when the opening balance is the last statement's closing balance", () => {
    expect(continuityFrom(me, { periodStart: "2026-10-01", periodEnd: "2026-10-31", openingBalance: 1, closingBalance: 10000000 }, null)).toEqual({
      errors: [],
      warnings: [],
    });
  });

  it("holds a statement that doesn't pick up where the one before left off", () => {
    const r = continuityFrom(me, { periodStart: "2026-10-01", periodEnd: "2026-10-31", openingBalance: 1, closingBalance: 9999900 }, null);
    expect(r.errors[0]).toMatch(/^Opening balance ₹1,00,000\.00 does not match the ₹99,999\.00 closing balance of the statement to 2026-10-31/);
  });

  it("checks an older month uploaded late against the month after it", () => {
    const r = continuityFrom(me, null, { periodStart: "2026-12-01", periodEnd: "2026-12-31", openingBalance: 18000000, closingBalance: 1 });
    expect(r.errors[0]).toMatch(/^Closing balance .* does not match .* opening balance of the statement from 2026-12-01/);
  });

  it("only warns about days no statement covers", () => {
    const r = continuityFrom(me, { periodStart: "2026-10-01", periodEnd: "2026-10-20", openingBalance: 1, closingBalance: 5 }, null);
    expect(r).toEqual({ errors: [], warnings: ["No statement covers 2026-10-21 → 2026-10-31: upload it to complete the account"] });
  });
});

describe("the same line from another file", () => {
  const ctx = { integrationId: "acc", statementId: "new", currency: "INR", statementDate: null, gmailMessageId: null, sourceSubject: null };
  const row = (over: Partial<Parameters<typeof toTransactionData>[0]> = {}) =>
    toTransactionData(
      { rowIndex: 0, txnDate: "2026-11-03", valueDate: null, description: "NEFT CR-TEST", referenceNumber: "X1", chequeNumber: null, debit: 0, credit: 5000000, balance: 18422000, rawText: "", ...over },
      ctx,
    );
  const existing = (over: Partial<{ debitAmount: string; creditAmount: string; runningBalance: string | null; transactionHash: string }> = {}) => ({
    txnDate: new Date("2026-11-03T00:00:00Z"),
    debitAmount: "0.00",
    creditAmount: "50000.00",
    runningBalance: "184220.00",
    transactionHash: "from-the-pdf",
    ...over,
  });

  it("skips a line the PDF of the same day already brought in, worded differently", () => {
    expect(knownLines([row({ description: "NEFT CR-TEST0000123-TEST PARENT" })], [existing()])).toEqual(new Set([0]));
  });

  it("keeps a different line: other amount, other balance, or no balance to compare", () => {
    expect(knownLines([row({ credit: 4000000 })], [existing()])).toEqual(new Set());
    expect(knownLines([row({ balance: 18422001 })], [existing()])).toEqual(new Set());
    expect(knownLines([row({ balance: null })], [existing({ runningBalance: null })])).toEqual(new Set());
  });

  it("lets one existing line account for one incoming row only", () => {
    expect(knownLines([row({ referenceNumber: "A" }), row({ referenceNumber: "B" })], [existing()])).toEqual(new Set([0]));
  });

  it("uses an exact hash match first, so it doesn't use up another row's line", () => {
    const a = row({ referenceNumber: "A" });
    const b = row({ referenceNumber: "B" });
    expect(knownLines([a, b], [existing({ transactionHash: b.transactionHash })])).toEqual(new Set([1]));
  });
});

describe("references in Axis's slash-separated narrations", () => {
  it("finds the UPI reference and the payer", () => {
    const n = "UPI/P2A/612345678901/TEST CANDIDATE/AXISBANK/Course fee";
    expect(classifyNarration(n)).toBe("UPI");
    expect(extractCounterparty(n, "UPI")).toEqual({ counterpartyName: "TEST CANDIDATE", upiReference: "612345678901", bankReference: null });
  });

  it("finds the IMPS / NEFT reference and the counterparty, skipping routing codes and IFSCs", () => {
    expect(extractCounterparty("IMPS/P2A/612345678901/TEST PARENT/HDFC BANK/", "IMPS")).toEqual({
      counterpartyName: "TEST PARENT",
      upiReference: null,
      bankReference: "612345678901",
    });
    expect(extractCounterparty("NEFT/HDFCN52026111234/TEST VENDOR/HDFC0000001/", "NEFT")).toMatchObject({
      counterpartyName: "TEST VENDOR",
      bankReference: "HDFCN52026111234",
    });
  });

  it("leaves HDFC's dash-separated narrations to the existing rules", () => {
    expect(extractCounterparty("NEFT CR-HDFC0000001-TEST PARENT-HDFCN52026111234", "NEFT")).toMatchObject({ bankReference: "HDFCN52026111234" });
  });
});
